-- Group advising records are independent from course enrollments.  RLS and
-- composite foreign keys keep each teacher's data and roster relationships separate.
create table public.advising_groups (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 120),
  cohort text not null default '' check (length(cohort) <= 120),
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (id, owner_id)
);

create table public.advising_students (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  group_id bigint not null,
  student_number text not null check (length(btrim(student_number)) between 1 and 40),
  full_name text not null check (length(btrim(full_name)) between 1 and 200),
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (group_id, student_number),
  unique (id, group_id, owner_id),
  foreign key (group_id, owner_id) references public.advising_groups(id, owner_id) on delete cascade
);

create table public.advising_sessions (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid(),
  group_id bigint not null,
  meeting_date date not null,
  start_time time,
  end_time time,
  location text not null default '' check (length(location) <= 300),
  advisors text[] not null default '{}' check (coalesce(array_length(advisors, 1), 0) <= 3 and length(array_to_string(advisors, '')) <= 600),
  discussion text not null default '' check (length(discussion) <= 20000),
  recommendations text not null default '' check (length(recommendations) <= 20000),
  next_meeting_date date,
  next_meeting_time time,
  next_meeting_note text not null default '' check (length(next_meeting_note) <= 1000),
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (id, group_id, owner_id),
  foreign key (group_id, owner_id) references public.advising_groups(id, owner_id) on delete cascade,
  check (start_time is null or end_time is null or end_time > start_time)
);

create table public.advising_participants (
  owner_id uuid not null default auth.uid(),
  group_id bigint not null,
  session_id bigint not null,
  student_id bigint not null,
  student_number_snapshot text not null check (length(btrim(student_number_snapshot)) between 1 and 40),
  full_name_snapshot text not null check (length(btrim(full_name_snapshot)) between 1 and 200),
  attendance_status text not null default 'not_recorded'
    check (attendance_status in ('not_recorded', 'present', 'absent', 'leave')),
  created_at timestamptz not null default now(),
  primary key (session_id, student_id),
  foreign key (session_id, group_id, owner_id) references public.advising_sessions(id, group_id, owner_id) on delete cascade,
  foreign key (student_id, group_id, owner_id) references public.advising_students(id, group_id, owner_id) on delete restrict
);

create index advising_groups_owner_idx on public.advising_groups(owner_id, is_archived, created_at desc);
create index advising_students_group_idx on public.advising_students(group_id, owner_id, is_archived);
create index advising_sessions_group_idx on public.advising_sessions(group_id, owner_id, meeting_date desc);
create index advising_participants_session_idx on public.advising_participants(session_id, owner_id);
create index advising_participants_student_fk_idx on public.advising_participants(student_id, group_id, owner_id);

alter table public.advising_groups enable row level security;
alter table public.advising_students enable row level security;
alter table public.advising_sessions enable row level security;
alter table public.advising_participants enable row level security;

-- Only an authenticated teacher may read or change their own advising records.
create policy advising_groups_owner on public.advising_groups for all to authenticated
  using (owner_id = (select auth.uid()) and exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'teacher'))
  with check (owner_id = (select auth.uid()) and exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'teacher'));
