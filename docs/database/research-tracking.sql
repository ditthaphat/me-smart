-- Teacher-owned research workspaces. No existing tables or records are changed.
create table public.research_projects (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references public.profiles(id),
  title text not null check (length(btrim(title)) between 1 and 240),
  members text not null default '' check (length(members) <= 4000),
  project_stage text not null default 'planning' check (project_stage in ('planning', 'active', 'defended', 'article', 'finished')),
  article_title text not null default '' check (length(article_title) <= 400),
  publication_target text not null default '' check (length(publication_target) <= 400),
  article_due_date date,
  external_url text not null default '' check (length(external_url) <= 2000 and (external_url = '' or external_url ~ '^https://')),
  notes text not null default '' check (length(notes) <= 4000),
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (id, owner_id)
);

create table public.research_tasks (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references public.profiles(id),
  project_id bigint not null,
  category text not null check (category in ('research', 'article')),
  title text not null check (length(btrim(title)) between 1 and 240),
  assignee text not null default '' check (length(assignee) <= 400),
  start_date date,
  due_date date,
  progress integer not null default 0 check (progress between 0 and 100),
  weight numeric(8,2) not null default 1 check (weight > 0 and weight <= 1000),
  notes text not null default '' check (length(notes) <= 4000),
  external_url text not null default '' check (length(external_url) <= 2000 and (external_url = '' or external_url ~ '^https://')),
  created_at timestamptz not null default now(),
  constraint research_tasks_project_owner_fkey foreign key (project_id, owner_id)
    references public.research_projects(id, owner_id) on delete cascade,
  check (start_date is null or due_date is null or start_date <= due_date)
);

create index research_projects_owner_idx on public.research_projects(owner_id, is_archived, id);
create index research_tasks_owner_project_idx on public.research_tasks(owner_id, project_id, category, due_date);
alter table public.research_projects enable row level security;
alter table public.research_tasks enable row level security;
revoke all on public.research_projects, public.research_tasks from public, anon;
grant select, insert, update, delete on public.research_projects, public.research_tasks to authenticated;
grant usage, select on sequence public.research_projects_id_seq, public.research_tasks_id_seq to authenticated;

create policy research_projects_owner_select on public.research_projects for select to authenticated
  using (owner_id = (select auth.uid()));
create policy research_projects_owner_insert on public.research_projects for insert to authenticated
  with check (owner_id = (select auth.uid()) and exists(select 1 from public.profiles where id = (select auth.uid()) and role = 'teacher'));
create policy research_projects_owner_update on public.research_projects for update to authenticated
  using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
create policy research_projects_owner_delete on public.research_projects for delete to authenticated
  using (owner_id = (select auth.uid()));

create policy research_tasks_owner_select on public.research_tasks for select to authenticated
  using (owner_id = (select auth.uid()));
create policy research_tasks_owner_insert on public.research_tasks for insert to authenticated
  with check (owner_id = (select auth.uid()) and exists(select 1 from public.profiles where id = (select auth.uid()) and role = 'teacher'));
create policy research_tasks_owner_update on public.research_tasks for update to authenticated
  using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
create policy research_tasks_owner_delete on public.research_tasks for delete to authenticated
  using (owner_id = (select auth.uid()));
