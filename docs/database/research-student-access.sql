create or replace function private.research_can_view_task(p_task bigint) returns boolean
language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.research_tasks t
 join public.research_projects p on p.id=t.project_id
 join public.research_memberships m on m.project_id=p.id
 where t.id=p_task and t.shared_with_students and not p.is_archived
 and m.student_id=(select auth.uid()) and m.status='approved'
 and (t.assigned_to is null or t.assigned_to=(select auth.uid())))
$$;
revoke all on function private.research_can_view_task(bigint) from public,anon;
grant execute on function private.research_can_view_task(bigint) to authenticated;
create policy research_reports_owner_read on public.research_task_reports for select to authenticated
 using (exists(select 1 from public.research_tasks t where t.id=task_id and t.owner_id=(select auth.uid())));
create policy research_reports_author_read on public.research_task_reports for select to authenticated
 using (author_id=(select auth.uid()) and private.research_can_view_task(task_id));
create policy research_reports_author_insert on public.research_task_reports for insert to authenticated
 with check (author_id=(select auth.uid()) and private.research_can_view_task(task_id));

create or replace function public.research_set_join_code(p_project_id bigint,p_code text) returns text
language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or not exists(select 1 from public.research_projects p where p.id=p_project_id and p.owner_id=auth.uid() and not p.is_archived) then raise exception 'Project unavailable'; end if;
 if p_code is null or p_code !~ '^[A-Za-z0-9_-]{8,64}$' then raise exception 'Code must be 8-64 English letters, numbers, _ or -'; end if;
 insert into private.research_join_codes(project_id,code_hash) values(p_project_id,extensions.crypt(p_code,extensions.gen_salt('bf')))
 on conflict(project_id) do update set code_hash=excluded.code_hash;
 return 'saved';
end $$;

create or replace function public.request_research_membership(p_project_id bigint,p_code text) returns text
language plpgsql security definer set search_path='' as $$
declare v_hash text; v_count integer; v_status text;
begin
 if auth.uid() is null or not exists(select 1 from public.profiles where id=auth.uid() and role='student' and student_id is not null) then raise exception 'Student account required'; end if;
 insert into private.research_join_attempts(user_id,started_at,attempts) values(auth.uid(),now(),1)
 on conflict(user_id) do update set
  attempts=case when private.research_join_attempts.started_at < now()-interval '15 minutes' then 1 else private.research_join_attempts.attempts+1 end,
  started_at=case when private.research_join_attempts.started_at < now()-interval '15 minutes' then now() else private.research_join_attempts.started_at end
 returning attempts into v_count;
 if v_count>10 then return 'rate_limited'; end if;
 if p_project_id is null or p_code is null or p_code !~ '^[A-Za-z0-9_-]{8,64}$' then return 'invalid'; end if;
 select j.code_hash into v_hash from private.research_join_codes j join public.research_projects p on p.id=j.project_id where p.id=p_project_id and not p.is_archived;
 if v_hash is null or v_hash <> extensions.crypt(p_code,v_hash) then return 'invalid'; end if;
 delete from private.research_join_attempts where user_id=auth.uid();
 select status into v_status from public.research_memberships where project_id=p_project_id and student_id=auth.uid();
 if v_status in ('approved','pending') then return v_status; end if;
 insert into public.research_memberships(project_id,student_id,status) values(p_project_id,auth.uid(),'pending')
 on conflict(project_id,student_id) do update set status='pending',requested_at=now(),decided_at=null
 where research_memberships.status='rejected' returning status into v_status;
 if v_status is null then select status into v_status from public.research_memberships where project_id=p_project_id and student_id=auth.uid(); end if;
 return v_status;
end $$;

create or replace function public.research_member_list(p_project_id bigint)
returns table(student_id uuid,student_number text,full_name text,status text,requested_at timestamptz)
language plpgsql stable security definer set search_path='' as $$
begin
 if auth.uid() is null or not exists(select 1 from public.research_projects where id=p_project_id and owner_id=auth.uid()) then raise exception 'Project unavailable'; end if;
 return query select m.student_id,p.student_id,p.full_name,m.status,m.requested_at from public.research_memberships m join public.profiles p on p.id=m.student_id where m.project_id=p_project_id order by p.student_id,p.full_name;
end $$;

create or replace function public.research_decide_member(p_project_id bigint,p_student_id uuid,p_approve boolean) returns text
language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or p_approve is null or not exists(select 1 from public.research_projects where id=p_project_id and owner_id=auth.uid() and not is_archived) then raise exception 'Project unavailable'; end if;
 update public.research_memberships set status=case when p_approve then 'approved' else 'rejected' end,decided_at=now() where project_id=p_project_id and student_id=p_student_id;
 if not found then raise exception 'Membership unavailable'; end if;
 return 'saved';
end $$;

create or replace function public.my_research_projects()
returns table(project_id bigint,title text,project_stage text,article_title text,publication_target text,article_due_date date,membership_status text)
language sql stable security definer set search_path='' as $$
 select p.id,p.title,case when m.status='approved' then p.project_stage else '' end,
 case when m.status='approved' then p.article_title else '' end,
 case when m.status='approved' then p.publication_target else '' end,
 case when m.status='approved' then p.article_due_date else null end,m.status
 from public.research_memberships m join public.research_projects p on p.id=m.project_id
 where m.student_id=(select auth.uid()) and m.status in ('pending','approved') and not p.is_archived order by p.created_at desc
$$;

create or replace function public.my_research_tasks(p_project_id bigint)
returns table(id bigint,project_id bigint,title text,category text,assignee text,start_date date,due_date date,progress integer,notes text,external_url text,assigned_to uuid)
language sql stable security definer set search_path='' as $$
 select t.id,t.project_id,t.title,t.category,t.assignee,t.start_date,t.due_date,t.progress,t.notes,t.external_url,t.assigned_to
 from public.research_tasks t where t.project_id=p_project_id and private.research_can_view_task(t.id) order by t.created_at,t.id
$$;

create or replace function public.research_review_report(p_report_id bigint,p_accept boolean,p_feedback text default '') returns text
language plpgsql security definer set search_path='' as $$
declare v_report public.research_task_reports%rowtype; v_owner uuid;
begin
 if auth.uid() is null or p_accept is null or length(coalesce(p_feedback,''))>4000 then raise exception 'Invalid request'; end if;
 select * into v_report from public.research_task_reports where id=p_report_id for update;
 if not found then raise exception 'Report unavailable'; end if;
 select owner_id into v_owner from public.research_tasks where id=v_report.task_id;
 if v_owner is distinct from auth.uid() or v_report.status<>'pending' then raise exception 'Report unavailable'; end if;
 if p_accept then update public.research_tasks set progress=v_report.progress where id=v_report.task_id and owner_id=auth.uid(); end if;
 update public.research_task_reports set status=case when p_accept then 'accepted' else 'needs_changes' end,feedback=coalesce(p_feedback,''),reviewed_at=now() where id=p_report_id;
 return 'saved';
end $$;

