-- Additive gradebook tables. Attendance remains the source of truth.
create table public.gradebook_settings (
  course_id bigint primary key references public.courses(id) on delete cascade,
  expected_sessions integer not null check (expected_sessions between 1 and 200),
  attendance_weight numeric(6,2) not null check (attendance_weight between 0 and 100),
  homework_weight numeric(6,2) not null check (homework_weight between 0 and 100),
  project_weight numeric(6,2) not null check (project_weight between 0 and 100),
  posttest_weight numeric(6,2) not null check (posttest_weight between 0 and 100),
  midterm_weight numeric(6,2) not null check (midterm_weight between 0 and 100),
  final_weight numeric(6,2) not null check (final_weight between 0 and 100),
  late_credit numeric(4,2) not null check (late_credit between 0 and 1),
  leave_credit numeric(4,2) not null check (leave_credit between 0 and 1),
  grade_a numeric(6,2) not null, grade_bplus numeric(6,2) not null,
  grade_b numeric(6,2) not null, grade_cplus numeric(6,2) not null,
  grade_c numeric(6,2) not null, grade_dplus numeric(6,2) not null,
  grade_d numeric(6,2) not null,
  updated_at timestamptz not null default now(),
  check (attendance_weight + homework_weight + project_weight + posttest_weight + midterm_weight + final_weight = 100),
  check (grade_a <= 100 and grade_a > grade_bplus and grade_bplus > grade_b and grade_b > grade_cplus
    and grade_cplus > grade_c and grade_c > grade_dplus and grade_dplus > grade_d and grade_d >= 0)
);

create table public.gradebook_items (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  category text not null check (category in ('homework','project','posttest','midterm','final')),
  title text not null check (length(trim(title)) between 1 and 80),
  max_score numeric(10,4) not null check (max_score > 0 and max_score <= 10000),
  position integer not null default 0,
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (id, course_id),
  unique (course_id, category, title)
);
create index gradebook_items_course_idx on public.gradebook_items(course_id, category, position, id);

create table public.gradebook_marks (
  course_id bigint not null,
  item_id bigint not null,
  student_id uuid not null,
  submitted boolean,
  score numeric(10,4),
  updated_at timestamptz not null default now(),
  primary key (item_id, student_id),
  foreign key (item_id, course_id) references public.gradebook_items(id, course_id) on delete cascade,
  foreign key (course_id, student_id) references public.enrollments(course_id, student_id) on delete cascade,
  check ((submitted is not null and score is null) or (submitted is null and score is not null)),
  check (score is null or score >= 0)
);
create index gradebook_marks_course_idx on public.gradebook_marks(course_id, item_id, student_id);

create function public.gradebook_validate_mark() returns trigger
language plpgsql security invoker set search_path = '' as $$
declare item_category text; item_max numeric;
begin
  select category, max_score into item_category, item_max
    from public.gradebook_items where id = new.item_id and course_id = new.course_id;
  if item_category is null then raise exception 'Gradebook item not found'; end if;
  if item_category = 'homework' and (new.submitted is null or new.score is not null) then
    raise exception 'Homework requires a submitted status';
  end if;
  if item_category <> 'homework' and (new.submitted is not null or new.score is null or new.score > item_max) then
    raise exception 'Score must be within the maximum';
  end if;
  new.updated_at := now();
  return new;
end $$;
revoke all on function public.gradebook_validate_mark() from public;
create trigger gradebook_validate_mark before insert or update on public.gradebook_marks
  for each row execute function public.gradebook_validate_mark();

create function public.gradebook_validate_item_change() returns trigger
language plpgsql security invoker set search_path = '' as $$
begin
  if (new.course_id <> old.course_id or new.category <> old.category or new.max_score < old.max_score)
     and exists (select 1 from public.gradebook_marks m where m.item_id = old.id
       and (new.course_id <> old.course_id or new.category <> old.category or m.score > new.max_score)) then
    raise exception 'Existing marks conflict with this item change';
  end if;
  return new;
end $$;
revoke all on function public.gradebook_validate_item_change() from public;
create trigger gradebook_validate_item_change before update on public.gradebook_items
  for each row execute function public.gradebook_validate_item_change();

alter table public.gradebook_settings enable row level security;
alter table public.gradebook_items enable row level security;
alter table public.gradebook_marks enable row level security;
revoke all on public.gradebook_settings, public.gradebook_items, public.gradebook_marks from public, anon, authenticated;
grant select, insert, update on public.gradebook_settings, public.gradebook_items, public.gradebook_marks to authenticated;
grant delete on public.gradebook_marks to authenticated;
grant usage, select on sequence public.gradebook_items_id_seq to authenticated;

create policy gradebook_settings_teacher on public.gradebook_settings for all to authenticated
  using (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid())))
  with check (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid())));
create policy gradebook_items_teacher on public.gradebook_items for all to authenticated
  using (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid())))
  with check (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid())));
create policy gradebook_marks_teacher on public.gradebook_marks for select to authenticated
  using (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid())));
create policy gradebook_marks_insert on public.gradebook_marks for insert to authenticated
  with check (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid()))
    and exists (select 1 from public.enrollments e where e.course_id = gradebook_marks.course_id
      and e.student_id = gradebook_marks.student_id and e.status = 'approved'));
create policy gradebook_marks_update on public.gradebook_marks for update to authenticated
  using (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid())))
  with check (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid()))
    and exists (select 1 from public.enrollments e where e.course_id = gradebook_marks.course_id
      and e.student_id = gradebook_marks.student_id and e.status = 'approved'));
create policy gradebook_marks_delete on public.gradebook_marks for delete to authenticated
  using (exists (select 1 from public.courses c where c.id = course_id and c.teacher_id = (select auth.uid())));
